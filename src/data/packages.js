export function getPackageThemes(pkg) {
  const themes = ['family', 'honeymoon']; // All packages are family and honeymoon-friendly by default
  
  // Weekend theme: 2 Nights or 3 Nights (for shimla/manali), or 4 Nights (for combo as the shortest combo trip)
  if (
    pkg.duration.includes('2 Nights') || 
    pkg.duration.includes('3 Nights') || 
    (pkg.category === 'combo' && pkg.duration.includes('4 Nights'))
  ) {
    themes.push('weekend');
  }
  
  // Adventure theme: contains Manali, Rohtang, adventure, glaciers
  const textToSearch = (pkg.title + ' ' + pkg.tagline + ' ' + pkg.overview).toLowerCase();
  if (textToSearch.includes('manali') || textToSearch.includes('adventure') || textToSearch.includes('glacier') || textToSearch.includes('ropeway') || textToSearch.includes('snow')) {
    themes.push('adventure');
  }
  
  // Luxury theme: starts from high price, or premium badge
  const priceInt = parseInt(pkg.price.replace(/[^0-9]/g, ''), 10);
  if (priceInt >= 25000 || pkg.badge.toLowerCase().includes('premium')) {
    themes.push('luxury');
  }
  
  if (pkg.category === 'combo') {
    themes.push('circuit');
  }
  
  return themes;
}
